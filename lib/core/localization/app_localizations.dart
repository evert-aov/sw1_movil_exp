        _localizedValues['es']?[key] ??
        key;
  }

  /// Traduce la etiqueta de categoría general ('Todos' / 'All') manteniendo intactas las categorías dinámicas de la API.
  String translateCategory(String rawCategory) {
    if (rawCategory == 'Todos') {
      return tr('cat_all');
    }
    return rawCategory;
  }
